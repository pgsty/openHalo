# The raw prepared result must retain the same microseconds as the text result.
@test('F13 prepared temporal metadata and bytes preserve precision')
def _():
    q(c,'create table precision_values(t0 datetime(0), t3 datetime(3), t6 datetime(6))')
    q(c,"insert into precision_values values('2026-01-02 03:04:05.123456','2026-01-02 03:04:05.123456','2026-01-02 03:04:05.123456')")
    c._execute_command(0x16,b'select t0,t3,t6 from precision_values')
    reply=c._read_packet().get_all_data()
    sid,ncols,nparams=struct.unpack('<IHH',reply[1:9])
    assert (ncols,nparams)==(3,0),(ncols,nparams)
    metadata=[c._read_packet().get_all_data() for _ in range(ncols)]
    assert [x[-3] for x in metadata]==[0,3,6],metadata
    c._read_packet()  # EOF, PyMySQL does not negotiate deprecate-EOF.
    c._execute_command(0x17,struct.pack('<IBI',sid,0,1))
    assert c._read_packet().get_all_data()==b'\x03'
    for _ in range(ncols+1): c._read_packet()
    row=c._read_packet().get_all_data(); offset=2; micros=[]
    for _ in range(3):
        length=row[offset];offset+=1
        micros.append(struct.unpack('<I',row[offset+7:offset+11])[0] if length==11 else 0)
        offset+=length
    c._read_packet()
    eq(micros,[0,123000,123456])
    c._execute_command(0x1f,b'');c._read_ok_packet()
    try:
        c._execute_command(0x17,struct.pack('<IBI',sid,0,1));c._read_packet()
    except pymysql.MySQLError as exc: eq(exc.args[0],1243)
    else: raise AssertionError('RESET retained a prepared handle')

